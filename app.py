def normalize_message(message):
    text = unicodedata.normalize("NFKC", message).casefold()
    text = "".join(
        character
        if character.isspace() or unicodedata.category(character)[0] in "LMN"
        else " "
        for character in text
    )
    return " ".join(text.split())


def detect_language(message):
    for character in message:
        codepoint = ord(character)
        if 0x0B80 <= codepoint <= 0x0BFF:
            return "ta"
        if 0x0900 <= codepoint <= 0x097F:
            return "hi"
        if 0x0C00 <= codepoint <= 0x0C7F:
            return "te"
        if 0x0980 <= codepoint <= 0x09FF:
            return "bn"

    words = set(normalize_message(message).split())
    if words.intersection({"mujhe", "chahiye", "chahie", "milega"}):
        return "hi"
    if words.intersection({"naku", "naaku", "kavali", "kaavali"}):
        return "te"
    if words.intersection({"amar", "amaar", "dorkar", "lagbe"}):
        return "bn"
    if words.intersection({"enakku", "venum", "vendum", "epdi", "panradhu"}):
        return "ta"
    return None


