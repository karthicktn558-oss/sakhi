@app.post("/api/ask")
def ask():
    data = request.get_json(silent=True) or {}
    message = data.get("message", "")
    preferred_language = data.get("language", "ta")
    if not isinstance(preferred_language, str) or preferred_language not in LANGUAGES:
        preferred_language = "ta"
    language_selected = data.get("language_selected") is True
    if not isinstance(message, str) or not message.strip():
        return jsonify({"error": RESPONSE_TEXT[preferred_language]["empty_error"]}), 400

    message = message.strip()[:1000]
    detected_language = detect_language(message)
    response_language = preferred_language if language_selected else detected_language or preferred_language
    service_id = classify_with_gemini(message) or classify_with_keywords(message)
    if service_id not in SERVICES:
        return jsonify({
            "service": None,
            "language": response_language,
            "message": RESPONSE_TEXT[response_language]["unclear_message"],
        })

    service = SERVICES[service_id]
    localized = {key: value[response_language] for key, value in service.items()}
    response_text = RESPONSE_TEXT[response_language]
    return jsonify({
        "service": service_id,
        "language": response_language,
        "name": localized["name"],
        "about": localized["about"],
        "eligibility": localized["eligibility"],
        "documents": localized["documents"],
        "steps": [step.format(place=localized["place"]) for step in response_text["steps"]],
        "next_steps": response_text["next_steps"],
        "help": response_text["help"].format(place=localized["place"]),
        "accuracy_note": response_text["accuracy_note"],
    })


